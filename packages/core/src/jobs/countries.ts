/** Every ISO-2 code we know a name for. */
export const ISO_COUNTRY_CODES: ReadonlySet<string> = new Set(Object.keys(NAMES));

/** Lowercase, accents removed, '&' → 'and', punctuation → space, whitespace collapsed. */
export function normalizePlaceName(name: string): string {
  return name
    .normalize('NFKD')
    .replace(/\p{M}+/gu, '')
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();
}

function buildNameTable(): ReadonlyMap<string, string> {
  const table = new Map<string, string>();
  for (const [cc, names] of Object.entries(NAMES)) {
    for (const name of names) {
      const key = normalizePlaceName(name);
      const prev = table.get(key);
      if (prev && prev !== cc) throw new Error(`countries.ts: "${name}" maps to ${prev} and ${cc}`);
      table.set(key, cc);
    }
  }
  return table;
}

/** normalized name → ISO-2 */
export const COUNTRY_NAME_TO_CODE = buildNameTable();

/** "Côte d'Ivoire" → 'CI', "Congo, The Democratic Republic of the" → 'CD'. Unknown → null. */
export function countryCodeFromName(name: string): string | null {
  return COUNTRY_NAME_TO_CODE.get(normalizePlaceName(name)) ?? null;
}

